import re
import pandas as pd
from google.colab import files

# Existing input file
clstr_file = "penam_AMR_90.fasta.clstr"

rows = []
current_cluster = None

with open(clstr_file, "r") as f:
    for line in f:
        line = line.strip()

        if line.startswith(">Cluster"):
            current_cluster = line[1:]

        else:
            match = re.search(r">(.+?)\.\.\.", line)
            if match and current_cluster is not None:
                sequence_id = match.group(1).split()[0]

                rows.append({
                    "Cluster_ID": current_cluster,
                    "Sequence_ID": sequence_id
                })

df = pd.DataFrame(rows)

# Output file
output_file = "cluster_members_long_format.csv"
df.to_csv(output_file, index=False)

print("Total sequences:", len(df))
print("Total clusters:", df["Cluster_ID"].nunique())
display(df.head(10))

files.download(output_file)