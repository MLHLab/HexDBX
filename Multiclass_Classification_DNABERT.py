def load_saved_model(model_dir="models", timestamp=None):
    """Load saved model for inference"""
    if timestamp is None:
        model_files = glob.glob(f"{model_dir}/model_info_*.json")
        if not model_files:
            print("No saved model found!")
            return None, None, None
        latest_file = max(model_files, key=os.path.getctime)
        with open(latest_file, 'r') as f:
            model_info = json.load(f)
    else:
        info_path = f"{model_dir}/model_info_{timestamp}.json"
        with open(info_path, 'r') as f:
            model_info = json.load(f)

    model = xgb.Booster()
    model.load_model(model_info['model_path'])
    scaler = joblib.load(model_info['scaler_path'])
    class_names = np.load(model_info['class_names_path'], allow_pickle=True)

    print(f"Model loaded successfully!")
    print(f"  - Number of classes: {model_info['num_classes']}")
    print(f"  - Class names: {class_names}")

    return model, scaler, class_names


def predict_with_model(model, scaler, X_new, class_names=None):
    """Make predictions with saved model"""
    X_scaled = scaler.transform(X_new)
    dtest = xgb.DMatrix(X_scaled)

    probs = model.predict(dtest)

    if len(probs.shape) == 1 and len(class_names) > 2:
        probs = probs.reshape(-1, len(class_names))

    preds = np.argmax(probs, axis=1) if len(probs.shape) > 1 else (probs > 0.5).astype(int)

    return preds, probs


