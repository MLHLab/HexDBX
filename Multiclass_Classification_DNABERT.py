class DNABERTFeatureExtractor(nn.Module):
    def __init__(self):
        super().__init__()
        self.bert = AutoModel.from_pretrained(Config.MODEL)

    def forward(self, ids, mask):
        outputs = self.bert(ids, attention_mask=mask)
        return outputs.last_hidden_state.mean(1)


def extract_features(model, dataloader, desc="Extracting features"):
    """Extract features from DNABERT model"""
    model.eval()
    features = []
    labels = []

    with torch.no_grad():
        for batch in tqdm(dataloader, desc=desc):
            ids = batch["ids"].to(Config.DEVICE)
            mask = batch["mask"].to(Config.DEVICE)

            feat = model(ids, mask)
            features.append(feat.cpu().numpy())

            if "label" in batch:
                labels.append(batch["label"].cpu().numpy())

    features = np.vstack(features)
    if labels:
        labels = np.concatenate(labels)
        return features, labels
    return features


