class DNADataset(Dataset):
    def __init__(self, seq, y=None):
        self.seq = seq
        self.y = y
        self.tokenizer = TOKENIZER

    def __len__(self):
        return len(self.seq)

    def __getitem__(self, idx):
        text = create_kmers(self.seq[idx])
        if not text.strip():
            text = "A A A A A A"

        enc = self.tokenizer(
            text,
            max_length=Config.MAX_LEN,
            padding="max_length",
            truncation=True,
            return_tensors="pt"
        )

        if self.y is not None:
            return {
                "ids": enc["input_ids"].squeeze(),
                "mask": enc["attention_mask"].squeeze(),
                "label": torch.tensor(self.y[idx], dtype=torch.long)
            }
        return {
            "ids": enc["input_ids"].squeeze(),
            "mask": enc["attention_mask"].squeeze()
        }


