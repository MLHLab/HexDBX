def plot_roc_curves(y_true, y_probs, fold, is_test=False, n_classes=6):
    """Plot and save ROC curves"""
    suffix = "test" if is_test else f"fold_{fold}"
    plt.figure(figsize=(12, 8))

    for i in range(min(n_classes, y_probs.shape[1])):
        try:
            binary_labels = (y_true == i).astype(int)
            if len(np.unique(binary_labels)) < 2:
                continue

            fpr, tpr, _ = roc_curve(binary_labels, y_probs[:, i])
            auc = roc_auc_score(binary_labels, y_probs[:, i])
            plt.plot(fpr, tpr, label=f'Class {i} (AUC = {auc:.3f})')

            tmp = pd.DataFrame({
                "fold": suffix,
                "class": i,
                "fpr": fpr,
                "tpr": tpr,
                "auc": auc
            })
            tmp.to_csv(f"outputs/roc/roc_{suffix}_class_{i}.csv", index=False)
        except:
            continue

    plt.plot([0, 1], [0, 1], 'k--', label='Random')
    plt.xlabel('False Positive Rate')
    plt.ylabel('True Positive Rate')
    plt.title(f'ROC Curves - {suffix.upper()} (XGBoost)')
    plt.legend()
    plt.grid(True, alpha=0.3)
    plt.tight_layout()
    plt.savefig(f"outputs/roc/roc_{suffix}_xgb.png", dpi=150, bbox_inches='tight')
    plt.close()


