class XGBoostClassifier:
    def __init__(self, num_classes, params=None):
        self.num_classes = num_classes
        self.params = params or self.get_default_params()
        self.models = []
        self.scaler = StandardScaler()

    def get_default_params(self):
        if self.num_classes > 2:
            objective = 'multi:softprob'
            eval_metric = 'mlogloss'
        else:
            objective = 'binary:logistic'
            eval_metric = 'logloss'

        return {
            'n_estimators': Config.XGB_N_ESTIMATORS,
            'max_depth': Config.XGB_MAX_DEPTH,
            'learning_rate': Config.XGB_LEARNING_RATE,
            'subsample': Config.XGB_SUBSAMPLE,
            'colsample_bytree': Config.XGB_COL_SAMPLE_BYTREE,
            'objective': objective,
            'eval_metric': eval_metric,
            'num_class': self.num_classes if self.num_classes > 2 else 1,
            'seed': Config.SEED,
            'verbosity': 0 if not Config.XGB_VERBOSE else 1,
            'n_jobs': -1,
            'tree_method': 'hist'
        }

    def train_fold(self, X_train, y_train, X_val, y_val, fold):
        """Train a single fold with proper train/validation split"""
        X_train_scaled = self.scaler.fit_transform(X_train)
        X_val_scaled = self.scaler.transform(X_val)

        dtrain = xgb.DMatrix(X_train_scaled, label=y_train)
        dval = xgb.DMatrix(X_val_scaled, label=y_val)

        evals = [(dtrain, 'train'), (dval, 'eval')]
        eval_result = {}

        model = xgb.train(
            self.params,
            dtrain,
            num_boost_round=self.params['n_estimators'],
            evals=evals,
            early_stopping_rounds=Config.XGB_EARLY_STOPPING_ROUNDS,
            verbose_eval=False,
            evals_result=eval_result
        )

        # Save training history
        train_loss = eval_result.get('train', {}).get(self.params['eval_metric'], [])
        val_loss = eval_result.get('eval', {}).get(self.params['eval_metric'], [])

        history_df = pd.DataFrame({
            'iteration': range(1, len(train_loss) + 1),
            'train_loss': train_loss,
            'val_loss': val_loss
        })

        history_df.to_csv(f"outputs/loss/xgb_loss_fold_{fold}.csv", index=False)

        # Plot loss
        plt.figure(figsize=(10, 6))
        plt.plot(history_df['iteration'], history_df['train_loss'],
                label='Training Loss', linewidth=2)
        plt.plot(history_df['iteration'], history_df['val_loss'],
                label='Validation Loss', linewidth=2)
        plt.xlabel('Iteration')
        plt.ylabel('Loss')
        plt.title(f'XGBoost Training History - Fold {fold}')
        plt.legend()
        plt.grid(True, alpha=0.3)
        plt.tight_layout()
        plt.savefig(f"outputs/loss/xgb_loss_fold_{fold}.png", dpi=150, bbox_inches='tight')
        plt.close()

        return model, self.scaler, history_df

    def predict_proba(self, X):
        """Predict probabilities using ensemble of models"""
        X_scaled = self.scaler.transform(X)
        dtest = xgb.DMatrix(X_scaled)

        all_probs = []
        for model in self.models:
            probs = model.predict(dtest)
            if self.num_classes > 2:
                probs = probs.reshape(-1, self.num_classes)
            else:
                probs = np.vstack([1-probs, probs]).T
            all_probs.append(probs)

        return np.mean(all_probs, axis=0)

    def predict(self, X):
        """Predict classes"""
        probs = self.predict_proba(X)
        return np.argmax(probs, axis=1)

    def get_feature_importance(self, importance_type='weight'):
        """Get average feature importance across all models"""
        importance_list = []
        for model in self.models:
            importance = model.get_score(importance_type=importance_type)
            importance_list.append(importance)

        avg_importance = {}
        for imp_dict in importance_list:
            for key, value in imp_dict.items():
                avg_importance[key] = avg_importance.get(key, 0) + value

        n_models = len(importance_list)
        for key in avg_importance:
            avg_importance[key] /= n_models

        return avg_importance


