def get_class_wise_performance(y_true, y_pred, class_names=None, prefix=""):
    """Calculate class-wise performance metrics"""
    n_classes = len(np.unique(y_true))

    precision, recall, f1, support = precision_recall_fscore_support(
        y_true, y_pred, average=None, zero_division=0
    )

    cm = confusion_matrix(y_true, y_pred)
    class_accuracy = np.diag(cm) / cm.sum(axis=1)

    results = pd.DataFrame({
        'class': [f'Class_{i}' for i in range(n_classes)],
        'precision': precision,
        'recall': recall,
        'f1_score': f1,
        'support': support,
        'accuracy': class_accuracy
    })

    if class_names is not None:
        results['class_name'] = [class_names[i] if i < len(class_names) else f'Class_{i}'
                                for i in range(n_classes)]

    # Calculate averages
    macro_precision = np.mean(precision)
    macro_recall = np.mean(recall)
    macro_f1 = np.mean(f1)
    weighted_precision = np.average(precision, weights=support)
    weighted_recall = np.average(recall, weights=support)
    weighted_f1 = np.average(f1, weights=support)

    avg_results = pd.DataFrame({
        'class': ['macro_avg', 'weighted_avg'],
        'precision': [macro_precision, weighted_precision],
        'recall': [macro_recall, weighted_recall],
        'f1_score': [macro_f1, weighted_f1],
        'support': [np.sum(support), np.sum(support)],
        'accuracy': [np.nan, np.nan]
    })

    results = pd.concat([results, avg_results], ignore_index=True)

    if prefix:
        results.to_csv(f"outputs/class_performance/class_performance_{prefix}.csv", index=False)

    return results


