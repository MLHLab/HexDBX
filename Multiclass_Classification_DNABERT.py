class Loader:
    def __init__(self, file):
        if file.endswith('.xlsx'):
            self.df = pd.read_excel(file, engine='openpyxl')
        elif file.endswith('.xls'):
            self.df = pd.read_excel(file)
        else:
            self.df = pd.read_csv(file)

    def load(self):
        seq_col = self.df.columns[0]
        class_col = self.df.columns[1]

        print(f"Sequence column: {seq_col}")
        print(f"Class column: {class_col}")

        # Clean sequences
        X_seq = (
            self.df[seq_col]
            .astype(str)
            .str.upper()
            .str.replace(r"[^ATCG]", "", regex=True)
            .tolist()
        )

        y = self.df[class_col].values

        # Encode labels
        if y.dtype == object:
            le = LabelEncoder()
            y = le.fit_transform(y)
            self.class_names = le.classes_
            print(f"Classes: {dict(zip(le.classes_, range(len(le.classes_))))}")
        else:
            self.class_names = np.unique(y)

        # Remove empty sequences
        valid_idx = [i for i, seq in enumerate(X_seq) if len(seq) > 0]
        X_seq = [X_seq[i] for i in valid_idx]
        y = y[valid_idx]

        num_classes = len(np.unique(y))
        print(f"Number of classes: {num_classes}")

        return X_seq, y, num_classes, self.class_names


