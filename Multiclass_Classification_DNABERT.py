    plt.tight_layout()
    plt.savefig(f"outputs/xgb/performance_comparison_{timestamp}.png", dpi=150, bbox_inches='tight')
    plt.close()

    print("\n" + "="*60)
    print("ALL RESULTS SAVED SUCCESSFULLY!")
    print("="*60)
    print("\nOutputs saved to:")
    print("  - outputs/features/ : Extracted features")
    print("  - outputs/xgb/ : XGBoost results")
