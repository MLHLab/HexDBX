    # STEP 1: Create train/test split
    # ============================================================
    print(f"\n{'='*50}")
    print("STEP 1: Creating Train/Test Split (80:20)")
    print(f"{'='*50}")

    X_train, X_test, y_train, y_test = train_test_split(
        X_seq, y,
        test_size=Config.TEST_SIZE,
        random_state=Config.SEED,
        stratify=y
    )

    print(f"Train samples: {len(X_train)} ({len(X_train)/len(X_seq)*100:.1f}%)")
    print(f"Test samples: {len(X_test)} ({len(X_test)/len(X_seq)*100:.1f}%)")

    # ============================================================
    # STEP 2: Extract features using DNABERT
    # ============================================================
    print(f"\n{'='*50}")
    print("STEP 2: Extracting DNABERT Features")
    print(f"{'='*50}")

    dnabert = DNABERTFeatureExtractor().to(Config.DEVICE)
    dnabert.eval()

    # Train features
    train_dataset = DNADataset(X_train, y_train)
    train_loader = DataLoader(
        train_dataset,
        batch_size=Config.BATCH,
        shuffle=False,
        pin_memory=True if torch.cuda.is_available() else False,
        num_workers=2
    )
    print("\nExtracting training features...")
    X_train_features, y_train_clean = extract_features(
        dnabert, train_loader, desc="Training features"
    )

    # Test features
    test_dataset = DNADataset(X_test, y_test)
    test_loader = DataLoader(
        test_dataset,
        batch_size=Config.BATCH,
        shuffle=False,
        pin_memory=True if torch.cuda.is_available() else False,
        num_workers=2
    )
    print("\nExtracting test features...")
    X_test_features, y_test_clean = extract_features(
        dnabert, test_loader, desc="Test features"
    )

    print(f"\nFeature dimension: {X_train_features.shape[1]}")
    print(f"Training features shape: {X_train_features.shape}")
    print(f"Test features shape: {X_test_features.shape}")

    # Save features
    pd.DataFrame(X_train_features).to_csv("outputs/features/train_features.csv", index=False)
    pd.DataFrame(X_test_features).to_csv("outputs/features/test_features.csv", index=False)
    pd.DataFrame(y_train_clean).to_csv("outputs/features/train_labels.csv", index=False)
    pd.DataFrame(y_test_clean).to_csv("outputs/features/test_labels.csv", index=False)

    # ============================================================
    # STEP 3: 5-Fold Cross-Validation
    # ============================================================
    print(f"\n{'='*50}")
    print(f"STEP 3: {Config.FOLDS}-Fold Cross-Validation")
    print(f"{'='*50}")

    skf = StratifiedKFold(n_splits=Config.FOLDS, shuffle=True, random_state=Config.SEED)
    fold_results = []
    xgb_models = []
    all_val_class_performance = []

    xgb_classifier = XGBoostClassifier(num_classes)

    for fold, (train_idx, val_idx) in enumerate(skf.split(X_train_features, y_train_clean), start=1):
        print(f"\n{'='*50}")
        print(f"FOLD {fold}/{Config.FOLDS}")
        print(f"{'='*50}")

        X_train_fold = X_train_features[train_idx]
        y_train_fold = y_train_clean[train_idx]
        X_val_fold = X_train_features[val_idx]
        y_val_fold = y_train_clean[val_idx]

        print(f"Train samples: {len(X_train_fold)}")
        print(f"Validation samples: {len(X_val_fold)}")

        # Train XGBoost
        model, scaler, history = xgb_classifier.train_fold(
            X_train_fold, y_train_fold, X_val_fold, y_val_fold, fold
        )
        xgb_models.append(model)

        # Predict on validation
        X_val_scaled = scaler.transform(X_val_fold)
        dval = xgb.DMatrix(X_val_scaled)

        if num_classes > 2:
            y_val_probs = model.predict(dval).reshape(-1, num_classes)
        else:
            y_val_probs = np.vstack([1 - model.predict(dval), model.predict(dval)]).T

        y_val_pred = np.argmax(y_val_probs, axis=1)

        # Compute class-wise performance
        val_class_perf = get_class_wise_performance(
            y_val_fold, y_val_pred, class_names, prefix=f"fold_{fold}_validation"
        )
        all_val_class_performance.append(val_class_perf)
        plot_class_wise_performance(val_class_perf, prefix=f"fold_{fold}_validation")

        # Compute metrics
        metrics = compute_metrics(y_val_fold, y_val_pred, y_val_probs)
        metrics["fold"] = fold
        fold_results.append(metrics)

        print(f"\nFold {fold} Validation Results:")
        for key, value in metrics.items():
            if key != "fold":
                print(f"  {key:18s}: {value:.4f}")

    # CV results
    cv_results_df = pd.DataFrame(fold_results)
    cv_mean = cv_results_df.mean(numeric_only=True)
    cv_std = cv_results_df.std(numeric_only=True)

    print(f"\n{'='*50}")
    print("Cross-Validation Performance (Mean ± Std):")
    print(f"{'='*50}")
    for metric in cv_mean.index:
        print(f"  {metric:18s}: {cv_mean[metric]:.4f} ± {cv_std[metric]:.4f}")

    # ============================================================
    # STEP 4: Train Final Model with Proper Validation Split
    # ============================================================
    print(f"\n{'='*50}")
    print("STEP 4: Training Final Model with Validation Split")
    print(f"{'='*50}")

    # Split training features for final model training (85/15 split)
    # This ensures NO DATA LEAKAGE - validation data is DIFFERENT from training data
    X_train_final, X_val_final, y_train_final, y_val_final = train_test_split(
        X_train_features, y_train_clean,
        test_size=Config.VAL_SIZE,  # 15% for validation during final training
        random_state=Config.SEED,
        stratify=y_train_clean
    )

    print(f"Final train samples: {len(X_train_final)}")
    print(f"Final validation samples: {len(X_val_final)}")

    # Train final model with PROPER validation data (DIFFERENT from training)
    xgb_final = XGBoostClassifier(num_classes)
    final_model, final_scaler, final_history = xgb_final.train_fold(
        X_train_final, y_train_final,    # ← Training data (85%)
        X_val_final, y_val_final,         # ← ✅ Different validation data (15%)
        fold="final"
    )
    xgb_final.models = [final_model]
    xgb_final.scaler = final_scaler

    # ============================================================
    # STEP 5: Evaluate on Test Set
    # ============================================================
    print(f"\n{'='*50}")
    print("STEP 5: Test Set Evaluation")
    print(f"{'='*50}")

    X_test_scaled = final_scaler.transform(X_test_features)
    dtest = xgb.DMatrix(X_test_scaled)

    if num_classes > 2:
        y_test_probs = final_model.predict(dtest).reshape(-1, num_classes)
    else:
        y_test_probs = np.vstack([1 - final_model.predict(dtest), final_model.predict(dtest)]).T

    y_test_pred = np.argmax(y_test_probs, axis=1)

    # Test performance
    test_class_perf = get_class_wise_performance(
        y_test_clean, y_test_pred, class_names, prefix="test"
    )
    plot_class_wise_performance(test_class_perf, prefix="test")

    test_metrics = compute_metrics(y_test_clean, y_test_pred, y_test_probs)

    print("\nTest Set Results:")
    for key, value in test_metrics.items():
        print(f"  {key:18s}: {value:.4f}")

    # Save test results
    save_predictions(y_test_clean, y_test_pred, y_test_probs, 0, is_test=True)
    plot_confusion_matrix(y_test_clean, y_test_pred, 0, is_test=True)
    plot_roc_curves(y_test_clean, y_test_probs, 0, is_test=True, n_classes=num_classes)

    # Classification report
    report = classification_report(y_test_clean, y_test_pred, output_dict=True)
    pd.DataFrame(report).transpose().to_csv("outputs/xgb/classification_report_test.csv")

    # ============================================================
    # STEP 6: Ensemble Prediction
    # ============================================================
    print(f"\n{'='*50}")
    print("STEP 6: Ensemble Prediction")
    print(f"{'='*50}")

    ensemble_classifier = XGBoostClassifier(num_classes)
    ensemble_classifier.models = xgb_models
    ensemble_classifier.scaler = final_scaler

    y_ensemble_probs = ensemble_classifier.predict_proba(X_test_features)
    y_ensemble_pred = np.argmax(y_ensemble_probs, axis=1)

    ensemble_class_perf = get_class_wise_performance(
        y_test_clean, y_ensemble_pred, class_names, prefix="ensemble_test"
    )
    plot_class_wise_performance(ensemble_class_perf, prefix="ensemble_test")

    ensemble_metrics = compute_metrics(y_test_clean, y_ensemble_pred, y_ensemble_probs)

    print("\nEnsemble Test Results:")
    for key, value in ensemble_metrics.items():
        print(f"  {key:18s}: {value:.4f}")

    # ============================================================
    # STEP 7: Save Comparison
    # ============================================================
    print(f"\n{'='*50}")
    print("STEP 7: Saving Validation vs Test Comparison")
    print(f"{'='*50}")

    # Average validation performance across folds
    all_val_numeric = []
    for df in all_val_class_performance:
        numeric_cols = ['precision', 'recall', 'f1_score', 'support', 'accuracy']
        df_numeric = df[['class'] + numeric_cols].copy()
        all_val_numeric.append(df_numeric)

    combined_val = pd.concat(all_val_numeric)
    avg_val_class_perf = combined_val.groupby('class').mean(numeric_only=True).reset_index()

    if 'class_name' in all_val_class_performance[0].columns:
        class_names_map = all_val_class_performance[0][['class', 'class_name']].drop_duplicates()
        avg_val_class_perf = avg_val_class_perf.merge(class_names_map, on='class', how='left')

    # Save comparisons
    save_class_wise_comparison(avg_val_class_perf, test_class_perf, prefix="best_model")
    save_class_wise_comparison(avg_val_class_perf, ensemble_class_perf, prefix="ensemble")

    # ============================================================
    # STEP 8: Save Final Model
    # ============================================================
    print(f"\n{'='*50}")
    print("STEP 8: Saving Final Model")
    print(f"{'='*50}")

    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")

    model_path, scaler_path, class_names_path = save_final_model(
        model=final_model,
        scaler=final_scaler,
        class_names=class_names,
        model_dir="models",
        timestamp=timestamp
    )

    # Feature importance
    importance = xgb_final.get_feature_importance()
    if importance:
        sorted_imp = sorted(importance.items(), key=lambda x: x[1], reverse=True)[:50]
        df_imp = pd.DataFrame(sorted_imp, columns=['feature', 'importance'])
        df_imp.to_csv('outputs/xgb/feature_importance.csv', index=False)

        plt.figure(figsize=(12, 8))
