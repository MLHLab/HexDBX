import pandas as pd
from Bio import SeqIO
import re

# Input files
csv_file = "tetracycline_output.csv"
fasta_file = "3tetracycline.fasta"

# Output files
cluster0_fasta = "cluster0_tetracycline.fasta"
other_fasta = "non_cluster0_tetracycline.fasta"

cluster0_excel = "cluster0_tetracycline_sequences.xlsx"
other_excel = "non_cluster0_tetracycline_sequences.xlsx"

# Read CSV
df = pd.read_csv(csv_file)

# Clean columns
df["Cluster_ID"] = df["Cluster_ID"].astype(str).str.strip()
df["Matched_Header"] = df["Matched_Header"].fillna("").astype(str).str.strip()

# Identify Cluster 0
is_cluster0 = df["Cluster_ID"].str.lower().isin(
    ["cluster 0", "cluster0", "0"]
)

df_cluster0 = df[is_cluster0].copy()
df_other = df[~is_cluster0].copy()

# Extract drug class from FASTA description
def extract_drug_class(description):
    match = re.search(r"(?:^|\|)drug_class=([^|\s]+)", description)
    return match.group(1) if match else "Unknown"

# Store extracted FASTA records and Excel rows
cluster0_records = []
other_records = []
cluster0_rows = []
other_rows = []

# Read FASTA and match CSV headers
for record in SeqIO.parse(fasta_file, "fasta"):
    description = record.description
    sequence = str(record.seq)
    drug_class = extract_drug_class(description)

    # Find matching CSV row(s)
    for group_df, records, rows in [
        (df_cluster0, cluster0_records, cluster0_rows),
        (df_other, other_records, other_rows)
    ]:
        matches = group_df[
            group_df["Matched_Header"].apply(
                lambda h: bool(h) and h in description
            )
        ]

        if not matches.empty:
            records.append(record)

            for _, csv_row in matches.iterrows():
                row = csv_row.to_dict()
                row["drug_class"] = drug_class
                row["FASTA_Header"] = description
                row["Sequence"] = sequence
                rows.append(row)

            break  # Each FASTA record goes into one cluster group

# Write FASTA files
SeqIO.write(cluster0_records, cluster0_fasta, "fasta")
SeqIO.write(other_records, other_fasta, "fasta")

# Create Excel dataframes
cluster0_output = pd.DataFrame(cluster0_rows)
other_output = pd.DataFrame(other_rows)

# Preserve useful columns even if no sequences matched
extra_columns = ["drug_class", "FASTA_Header", "Sequence"]

for output, source_df in [
    (cluster0_output, df_cluster0),
    (other_output, df_other)
]:
    for col in source_df.columns:
        if col not in output.columns:
            output[col] = pd.Series(dtype=object)
    for col in extra_columns:
        if col not in output.columns:
            output[col] = pd.Series(dtype=object)

# Save valid Excel files
cluster0_output.to_excel(cluster0_excel, index=False)
other_output.to_excel(other_excel, index=False)

# Summary
print("Extraction completed!")
print("Cluster 0 FASTA sequences:", len(cluster0_records))
print("Other-cluster FASTA sequences:", len(other_records))
print("Cluster 0 Excel rows:", len(cluster0_output))
print("Other-cluster Excel rows:", len(other_output))

print("\nOutput files:")
print(cluster0_fasta)
print(other_fasta)
print(cluster0_excel)
print(other_excel)