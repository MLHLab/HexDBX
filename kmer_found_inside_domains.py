import re


def find_kmers_in_sequence(sequence, kmers):
    """
    Search for each k-mer within a given biological sequence.

    The function checks every possible position in the sequence and
    records all occurrences of each k-mer.

    Parameters
    ----------
    sequence : str
        The reference DNA, RNA, or protein sequence to search.

    kmers : list of str
        A list containing the k-mer sequences to be searched for.

    Returns
    -------
    dict
        A dictionary containing:
        - found: k-mers that were detected, along with their positions
        - not_found: k-mers that were not detected
        - sequence_length: length of the input sequence

    Notes
    -----
    Positions are reported using zero-based indexing.
    For example, the first character of the sequence is position 0.
    """

    # Initialize the results dictionary.
    results = {
        "found": [],
        "not_found": [],
        "sequence_length": len(sequence)
    }

    # Search for each k-mer independently.
    for kmer in kmers:

        # Store all positions where the current k-mer is found.
        positions = []

        # Determine the length of the current k-mer.
        k = len(kmer)

        # Slide a window of size k across the sequence.
        for i in range(len(sequence) - k + 1):

            # Compare the sequence segment with the current k-mer.
            if sequence[i:i + k] == kmer:

                # Store the start and end positions of the occurrence.
                positions.append({
                    "position": i,
                    "end_position": i + k - 1
                })

        # If at least one occurrence was found, store the details.
        if positions:
            results["found"].append({
                "kmer": kmer,
                "length": k,
                "occurrences": len(positions),
                "positions": positions
            })

        # Otherwise, add the k-mer to the not-found list.
        else:
            results["not_found"].append(kmer)

    return results


def print_results(results):
    """
    Display the k-mer search results in a readable format.

    Parameters
    ----------
    results : dict
        Dictionary returned by find_kmers_in_sequence().
    """

    # Print the main results header.
    print("\n" + "=" * 70)
    print("KMER SEARCH RESULTS")
    print("=" * 70)

    # Display the length of the sequence.
    print(f"Sequence length: {results['sequence_length']} bp")
    print("-" * 70)

    # --------------------------------------------------
    # Display k-mers that were found.
    # --------------------------------------------------

    print(f"\nFOUND KMERS ({len(results['found'])}):")
    print("-" * 70)

    if results["found"]:

        for item in results["found"]:

            # Display basic information about the k-mer.
            print(
                f"\n  Kmer: {item['kmer']} "
                f"(length: {item['length']})"
            )

            print(f"  Occurrences: {item['occurrences']}")

            # Display the position of every occurrence.
            for pos in item["positions"]:
                print(
                    f"    -> Position: "
                    f"{pos['position']}-{pos['end_position']}"
                )

    else:
        print("  No kmers found in the sequence.")

    # --------------------------------------------------
    # Display k-mers that were not found.
    # --------------------------------------------------

    print(
        f"\nNOT FOUND KMERS ({len(results['not_found'])}):"
    )
    print("-" * 70)

    if results["not_found"]:

        for kmer in results["not_found"]:
            print(f"  {kmer}")

    else:
        print("  All kmers were found!")

    # Print the closing separator.
    print("\n" + "=" * 70)


def get_sequence_from_user():
    """
    Collect a biological sequence from the user.

    The user can paste the sequence over multiple lines.
    Input continues until an empty line is entered.

    Returns
    -------
    str
        Cleaned and uppercase biological sequence.
    """

    print("\n" + "=" * 70)
    print("KMER SEARCH TOOL")
    print("=" * 70)

    print("\nEnter your long sequence:")
    print("-" * 70)
    print("Paste your sequence below.")
    print("Press Enter twice when you have finished.")
    print("-" * 70)

    # Store individual lines of the sequence.
    lines = []

    while True:

        line = input()

        # An empty line indicates the end of the sequence.
        if line == "":
            break

        # Remove leading/trailing whitespace before storing the line.
        lines.append(line.strip())

    # Join all sequence lines into a single continuous sequence.
    sequence = "".join(lines)

    # Remove spaces and tabs, then convert to uppercase.
    sequence = (
        sequence
        .replace(" ", "")
        .replace("\t", "")
        .upper()
    )

    # Display basic information about the loaded sequence.
    print(f"\nSequence loaded: {len(sequence)} characters")
    print(f"First 50 characters: {sequence[:50]}...")

    return sequence


def get_kmers_from_user():
    """
    Collect 35 k-mers from the user.

    The user can enter k-mers as a comma-, semicolon-, space-,
    or newline-separated list. If fewer than 35 k-mers are
    provided, the program requests the remaining k-mers individually.

    Returns
    -------
    list of str
        List containing 35 k-mer sequences.
    """

    print("\n" + "=" * 70)
    print("Enter 35 kmers to search for:")
    print("-" * 70)
    print(
        "You can paste all k-mers at once, separated by commas, "
        "spaces, semicolons, or newlines."
    )
    print("-" * 70)

    # Ask the user to enter the k-mers in bulk.
    bulk_input = input("\nPaste your kmers: ").strip().upper()

    kmers = []

    if bulk_input:

        # Split the input using commas, semicolons, whitespace,
        # or newline characters.
        kmers = re.split(r"[,;\s]+", bulk_input)

        # Remove any empty entries.
        kmers = [kmer.strip() for kmer in kmers if kmer.strip()]

    # --------------------------------------------------
    # Request additional k-mers if fewer than 35 were entered.
    # --------------------------------------------------

    if len(kmers) < 35:

        remaining = 35 - len(kmers)

        print(
            f"\nOnly {len(kmers)} k-mers were entered. "
            f"Please enter the remaining {remaining}."
        )

        while len(kmers) < 35:

            kmer = input(
                f"Kmer {len(kmers) + 1}: "
            ).strip().upper()

            # Do not allow empty k-mers.
            if not kmer:
                print(
                    "Kmer cannot be empty. "
                    "Please enter a sequence."
                )
                continue

            # Remove spaces from an individually entered k-mer.
            kmer = kmer.replace(" ", "")

            # Add the k-mer to the list.
            kmers.append(kmer)

            print(
                f"Kmer {len(kmers)} added: "
                f"{kmer} (length: {len(kmer)})"
            )

    # --------------------------------------------------
    # Display the complete list of k-mers.
    # --------------------------------------------------

    print("\n" + "-" * 70)
    print(f"All {len(kmers)} kmers to search:")
    print("-" * 70)

    # Display five k-mers per row for better readability.
    for i in range(0, len(kmers), 5):

        row = []

        for j in range(i, min(i + 5, len(kmers))):
            row.append(f"{j + 1}.{kmers[j]}")

        print("  " + "  ".join(row))

    return kmers


def save_results(results, sequence, filename):
    """
    Save k-mer search results to a text file.

    Parameters
    ----------
    results : dict
        Results returned by find_kmers_in_sequence().

    sequence : str
        The sequence that was searched.

    filename : str
        Name of the output file.
    """

    # Open the output file for writing.
    with open(filename, "w") as file:

        # Write the main report header.
        file.write("=" * 70 + "\n")
        file.write("KMER SEARCH RESULTS\n")
        file.write("=" * 70 + "\n")

        # Write sequence information.
        file.write(
            f"Sequence length: {len(sequence)} bp\n\n"
        )

        # --------------------------------------------------
        # Write k-mers that were found.
        # --------------------------------------------------

        file.write("FOUND KMERS:\n")
        file.write("-" * 70 + "\n")

        for item in results["found"]:

            file.write(
                f"\nKmer: {item['kmer']} "
                f"(occurrences: {item['occurrences']})\n"
            )

            # Write the position of each occurrence.
            for pos in item["positions"]:

                file.write(
                    f"  Position: "
                    f"{pos['position']}-{pos['end_position']}\n"
                )

        # --------------------------------------------------
        # Write k-mers that were not found.
        # --------------------------------------------------

        file.write("\nNOT FOUND KMERS:\n")
        file.write("-" * 70 + "\n")

        for kmer in results["not_found"]:
            file.write(f"{kmer}\n")


