# ====================================================
# CONFIGURATION
# ====================================================

class SHAPConfig:
    MODEL_DIR = "models"
    OUTPUT_DIR = "outputs/shap_analysis"
    BACKGROUND_SAMPLES_PER_CLASS = 20
    TOP_FEATURES = 20
    TEST_DATA_PATH = "outputs/features/test_features.csv"
    TEST_LABELS_PATH = "outputs/features/test_labels.csv"


# Create output directories
os.makedirs(SHAPConfig.OUTPUT_DIR, exist_ok=True)
os.makedirs(f"{SHAPConfig.OUTPUT_DIR}/class_wise", exist_ok=True)
os.makedirs(f"{SHAPConfig.OUTPUT_DIR}/violin_plots", exist_ok=True)
os.makedirs(f"{SHAPConfig.OUTPUT_DIR}/summary_plots", exist_ok=True)


