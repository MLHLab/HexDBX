def main():
    print("\n" + "="*60)
    print("SHAP ANALYSIS FOR SAVED DNABERT-XGBoost MODEL")
    print("="*60)

    # Load model
    print("\n" + "-"*50)
    print("STEP 1: Loading Saved Model")
    print("-"*50)

    model, scaler, class_names, model_info = load_saved_model(SHAPConfig.MODEL_DIR)

    if model is None:
        print("ERROR: Could not load model. Please train the model first.")
        return

    # Load test data
    print("\n" + "-"*50)
    print("STEP 2: Loading Test Data")
    print("-"*50)

    X_test, y_test = load_test_data(
        SHAPConfig.TEST_DATA_PATH,
        SHAPConfig.TEST_LABELS_PATH
    )

    # Load training data for background
    print("\n" + "-"*50)
    print("STEP 3: Loading Training Data for Background")
    print("-"*50)

    train_features_path = "outputs/features/train_features.csv"
    train_labels_path = "outputs/features/train_labels.csv"

    if os.path.exists(train_features_path) and os.path.exists(train_labels_path):
        X_train = pd.read_csv(train_features_path).values
        y_train = pd.read_csv(train_labels_path).values.flatten()
        print(f"Training data loaded: {X_train.shape[0]} samples, {X_train.shape[1]} features")
    else:
        print("Training data not found. Using test data as background.")
        X_train = X_test
        y_train = y_test

    # Perform SHAP analysis
    print("\n" + "-"*50)
    print("STEP 4: Performing SHAP Analysis")
    print("-"*50)

    num_classes = len(class_names)
    shap_values, explainer = perform_shap_analysis(
        model, X_test, X_train, y_train, class_names, num_classes
    )

    # Save SHAP explainer
    print("\n" + "-"*50)
    print("STEP 5: Saving SHAP Explainer")
    print("-"*50)

    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    explainer_path = f"{SHAPConfig.OUTPUT_DIR}/shap_explainer_{timestamp}.joblib"
    joblib.dump(explainer, explainer_path)
    print(f"SHAP explainer saved to: {explainer_path}")

    # Summary
    print("\n" + "="*60)
    print("SHAP ANALYSIS COMPLETE")
    print("="*60)
    print(f"\nOutputs saved to: {SHAPConfig.OUTPUT_DIR}")
    print("\nFiles generated:")
    print("  - class_wise/")
    print("    * shap_values_class_*.csv - SHAP values for each class")
    print("    * class_wise_shap_importance.csv - Feature importance per class")
    print("    * avg_shap_per_class.csv - Average SHAP values per class")
    print("  - violin_plots/")
    print("    * shap_violin_class_*.png - Violin plots for each class")
    print("    * shap_violin_data_class_*.csv - Data for violin plots")
    print("    * shap_violin_top_feature_all_classes.png - Combined violin plot")
    print("  - summary_plots/")
    print("    * shap_summary_all_classes.png - Summary plot (all classes)")
    print("    * shap_bar_all_classes.png - Bar plot (all classes)")
    print("    * shap_summary_class_*.png - Summary plot for each class")
    print(f"  - shap_explainer_{timestamp}.joblib - SHAP explainer")

    return shap_values, explainer


# ====================================================
# RUN
# ====================================================

if __name__ == "__main__":
    shap_values, explainer = main()
    print("\n" + "="*60)
    print("SHAP ANALYSIS COMPLETED SUCCESSFULLY")
