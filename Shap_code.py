def get_class_wise_background(X_train, y_train, num_classes, samples_per_class=20):
    """Extract background samples: samples from each class"""
    background_indices = []

    for class_idx in range(num_classes):
        class_indices = np.where(y_train == class_idx)[0]
        n_samples = min(samples_per_class, len(class_indices))
        if n_samples > 0:
            sampled_indices = np.random.choice(class_indices, n_samples, replace=False)
            background_indices.extend(sampled_indices)
            print(f"  Class {class_idx}: {n_samples} samples")

    background_X = X_train[background_indices]
    background_y = y_train[background_indices]

    print(f"Background data: {len(background_X)} samples total")

    return background_X, background_y


def save_shap_values_correctly(shap_values, class_names, output_dir):
    """
    CORRECTED: Save SHAP values properly as numeric values, not strings
    """
    print(f"\nSaving SHAP values...")
    print(f"Type of shap_values: {type(shap_values)}")

    # Handle different types of shap_values
    if isinstance(shap_values, list):
        # Multi-class case
        print(f"Multi-class SHAP: {len(shap_values)} classes")

        for class_idx in range(len(shap_values)):
            # Get SHAP values for this class and ensure it's a numpy array
            shap_class = shap_values[class_idx]

            # Convert to numpy array if needed
            if not isinstance(shap_class, np.ndarray):
                shap_class = np.array(shap_class)

            # Ensure 2D array
            if len(shap_class.shape) == 1:
                shap_class = shap_class.reshape(-1, 1)

            print(f"  Class {class_idx} shape: {shap_class.shape}")

            # Create dataframe with proper numeric values
            n_features = shap_class.shape[1]
            column_names = [f'feature_{i}' for i in range(n_features)]

            # Create DataFrame directly from numpy array - this ensures numeric values
            shap_df = pd.DataFrame(shap_class, columns=column_names)

            # Add class info
            class_name = class_names[class_idx] if class_names is not None else f"Class_{class_idx}"
            shap_df['class_idx'] = class_idx
            shap_df['class_name'] = class_name

            # Verify data types
            for col in column_names:
                shap_df[col] = pd.to_numeric(shap_df[col], errors='coerce')

            # Save as CSV
            csv_path = f"{output_dir}/class_wise/shap_values_class_{class_idx}.csv"
            shap_df.to_csv(csv_path, index=False)
            print(f"  Saved SHAP values for {class_name} to {csv_path}")

            # Also save as numpy
            np.save(f"{output_dir}/class_wise/shap_values_class_{class_idx}.npy",
                   shap_class.astype(np.float32))

    else:
        # Binary classification or single array
        print("Binary classification or single SHAP array")

        # Convert to numpy array if needed
        if not isinstance(shap_values, np.ndarray):
            shap_values = np.array(shap_values)

        # Ensure 2D array
        if len(shap_values.shape) == 1:
            shap_values = shap_values.reshape(-1, 1)

        print(f"  SHAP shape: {shap_values.shape}")

        n_features = shap_values.shape[1]
        column_names = [f'feature_{i}' for i in range(n_features)]

        # Create DataFrame directly from numpy array
        shap_df = pd.DataFrame(shap_values, columns=column_names)

        # Verify data types
        for col in column_names:
            shap_df[col] = pd.to_numeric(shap_df[col], errors='coerce')

        shap_df.to_csv(f"{output_dir}/class_wise/shap_values.csv", index=False)
        np.save(f"{output_dir}/class_wise/shap_values.npy", shap_values.astype(np.float32))
        print(f"  Saved SHAP values to {output_dir}/class_wise/shap_values.csv")


def perform_shap_analysis(model, X_test, X_train, y_train, class_names, num_classes):
    """Perform SHAP analysis with class-wise background data"""
    print("\n" + "="*60)
    print("PERFORMING SHAP ANALYSIS")
    print("="*60)

    # Get class-wise background data
    print("\nSelecting background data (20 samples per class):")
    background_X, background_y = get_class_wise_background(
        X_train, y_train, num_classes,
        samples_per_class=SHAPConfig.BACKGROUND_SAMPLES_PER_CLASS
    )

    # Create SHAP explainer
    print("\nCreating SHAP explainer...")
    feature_names = [f'feature_{i}' for i in range(X_test.shape[1])]
    explainer = shap.TreeExplainer(model, background_X, feature_names=feature_names)

    # Calculate SHAP values
    print(f"Calculating SHAP values for {len(X_test)} test samples...")
    shap_values = explainer.shap_values(X_test)

    # Save SHAP values using corrected function
    save_shap_values_correctly(shap_values, class_names, SHAPConfig.OUTPUT_DIR)

    # Save class-wise feature importance
    print("\nSaving class-wise feature importance...")
    if isinstance(shap_values, list):
        n_classes = len(shap_values)
        class_wise_importance = []

        for class_idx in range(n_classes):
            shap_class = np.array(shap_values[class_idx])
            avg_importance = np.abs(shap_class).mean(axis=0)
            class_name = class_names[class_idx] if class_names is not None else f"Class_{class_idx}"

            for feat_idx, imp in enumerate(avg_importance):
                class_wise_importance.append({
                    'class_idx': class_idx,
                    'class_name': class_name,
                    'feature': f'feature_{feat_idx}',
                    'shap_importance': float(imp)
                })

        importance_df = pd.DataFrame(class_wise_importance)
        importance_path = f"{SHAPConfig.OUTPUT_DIR}/class_wise/class_wise_shap_importance.csv"
        importance_df.to_csv(importance_path, index=False)
        print(f"  Saved class-wise importance to {importance_path}")

        # Save average SHAP values per class
        print("\nSaving average SHAP values per class...")
        avg_shap_data = []

        for class_idx in range(n_classes):
            shap_class = np.array(shap_values[class_idx])
            avg_shap = shap_class.mean(axis=0)
            class_name = class_names[class_idx] if class_names is not None else f"Class_{class_idx}"

            row = {'class_idx': class_idx, 'class_name': class_name}
            for feat_idx, val in enumerate(avg_shap):
                row[f'feature_{feat_idx}'] = float(val)
            avg_shap_data.append(row)

        avg_shap_df = pd.DataFrame(avg_shap_data)
        avg_path = f"{SHAPConfig.OUTPUT_DIR}/class_wise/avg_shap_per_class.csv"
        avg_shap_df.to_csv(avg_path, index=False)
        print(f"  Saved average SHAP values to {avg_path}")

        # Generate violin plots
        print("\nGenerating violin plots...")
        generate_violin_plots(shap_values, X_test, class_names, n_classes)

        # Generate summary plots
        print("\nGenerating summary plots...")
        generate_summary_plots(shap_values, X_test, class_names, n_classes)

        return shap_values, explainer

    else:
        # Binary classification
        print("Binary classification SHAP")
        shap_array = np.array(shap_values)

        # Save average SHAP values
        avg_shap = shap_array.mean(axis=0)
        avg_df = pd.DataFrame([avg_shap], columns=[f'feature_{i}' for i in range(len(avg_shap))])
        avg_df.to_csv(f"{SHAPConfig.OUTPUT_DIR}/class_wise/avg_shap_values.csv", index=False)

        # Generate summary plot
        plt.figure(figsize=(12, 8))
        shap.summary_plot(shap_values, X_test, show=False)
        plt.tight_layout()
        plt.savefig(f"{SHAPConfig.OUTPUT_DIR}/summary_plots/shap_summary_plot.png",
                   dpi=150, bbox_inches='tight')
        plt.close()

        return shap_values, explainer


def generate_violin_plots(shap_values, X_test, class_names, num_classes):
    """Generate violin plots for each class"""
    if not isinstance(shap_values, list):
        return

    # Calculate average importance across all classes
    shap_array = np.array(shap_values[0])
    avg_importance = np.zeros(shap_array.shape[1])

    for class_idx in range(num_classes):
        shap_class = np.array(shap_values[class_idx])
        avg_importance += np.abs(shap_class).mean(axis=0)
    avg_importance /= num_classes

    # Get top features
    top_n = min(SHAPConfig.TOP_FEATURES, len(avg_importance))
    top_features = np.argsort(avg_importance)[::-1][:top_n]

    # Generate violin plots for each class
    print(f"  Generating {num_classes} class-wise violin plots...")

    for class_idx in range(num_classes):
        class_name = class_names[class_idx] if class_names is not None else f"Class_{class_idx}"

        # Prepare data - extract only top features
        shap_class = np.array(shap_values[class_idx])
        data_dict = {}

        for feat_idx in top_features:
            data_dict[f'feature_{feat_idx}'] = shap_class[:, feat_idx]

        data = pd.DataFrame(data_dict)

        # Verify data types
        for col in data.columns:
            data[col] = pd.to_numeric(data[col], errors='coerce')

        # Save data as CSV
        data_path = f"{SHAPConfig.OUTPUT_DIR}/violin_plots/shap_violin_data_class_{class_idx}.csv"
        data.to_csv(data_path, index=False)

        # Create violin plot
        fig, ax = plt.subplots(figsize=(14, 8))
        positions = np.arange(len(data.columns))
        parts = ax.violinplot(data.values, positions=positions, showmeans=True, showmedians=True)

        # Customize
        colors = plt.cm.Set3(np.linspace(0, 1, len(data.columns)))
        for i, pc in enumerate(parts['bodies']):
            pc.set_facecolor(colors[i % len(colors)])
            pc.set_alpha(0.7)

        parts['cmeans'].set_color('red')
        parts['cmeans'].set_marker('o')
        parts['cmeans'].set_markersize(6)
        parts['cmedians'].set_color('black')
        parts['cmedians'].set_marker('s')
        parts['cmedians'].set_markersize(5)

        ax.set_xticks(positions)
        ax.set_xticklabels(data.columns, rotation=45, ha='right')
        ax.set_ylabel('SHAP Value')
        ax.set_title(f'SHAP Value Distribution - {class_name}')
        ax.axhline(y=0, color='gray', linestyle='--', alpha=0.5)
        ax.grid(True, alpha=0.3)

        plt.tight_layout()
        plt.savefig(f"{SHAPConfig.OUTPUT_DIR}/violin_plots/shap_violin_class_{class_idx}.png",
                   dpi=150, bbox_inches='tight')
        plt.close()

        print(f"    Saved violin plot for {class_name}")

    # Generate combined violin plot
    print("  Generating combined violin plot...")
    top_feature = top_features[0]
    fig, ax = plt.subplots(figsize=(12, 6))

    data_all = []
    labels = []

    for class_idx in range(num_classes):
        class_name = class_names[class_idx] if class_names is not None else f"Class_{class_idx}"
        shap_class = np.array(shap_values[class_idx])
        data_all.append(shap_class[:, top_feature])
        labels.append(class_name)

    parts = ax.violinplot(data_all, positions=np.arange(len(data_all)), showmeans=True, showmedians=True)

    colors = plt.cm.Set3(np.linspace(0, 1, len(data_all)))
    for i, pc in enumerate(parts['bodies']):
        pc.set_facecolor(colors[i % len(colors)])
        pc.set_alpha(0.7)

    parts['cmeans'].set_color('red')
    parts['cmeans'].set_marker('o')
    parts['cmeans'].set_markersize(6)
    parts['cmedians'].set_color('black')
    parts['cmedians'].set_marker('s')
    parts['cmedians'].set_markersize(5)

    ax.set_xticks(np.arange(len(labels)))
    ax.set_xticklabels(labels, rotation=45, ha='right')
    ax.set_ylabel('SHAP Value')
    ax.set_title(f'SHAP Value Distribution for Top Feature (feature_{top_feature}) Across All Classes')
    ax.axhline(y=0, color='gray', linestyle='--', alpha=0.5)
    ax.grid(True, alpha=0.3)

    plt.tight_layout()
    plt.savefig(f"{SHAPConfig.OUTPUT_DIR}/violin_plots/shap_violin_top_feature_all_classes.png",
               dpi=150, bbox_inches='tight')
    plt.close()
    print("  Combined violin plot saved")


def generate_summary_plots(shap_values, X_test, class_names, num_classes):
    """Generate SHAP summary plots"""
    if not isinstance(shap_values, list):
        return

    # Summary plot - all classes combined
    try:
        plt.figure(figsize=(14, 10))
        shap.summary_plot(shap_values, X_test, show=False)
        plt.tight_layout()
        plt.savefig(f"{SHAPConfig.OUTPUT_DIR}/summary_plots/shap_summary_all_classes.png",
                   dpi=150, bbox_inches='tight')
        plt.close()
        print("  Saved summary plot (all classes)")
    except Exception as e:
        print(f"  Warning: Could not save summary plot: {e}")

    # Bar plot - all classes combined
    try:
        plt.figure(figsize=(14, 10))
        shap.summary_plot(shap_values, X_test, plot_type="bar", show=False)
        plt.tight_layout()
        plt.savefig(f"{SHAPConfig.OUTPUT_DIR}/summary_plots/shap_bar_all_classes.png",
                   dpi=150, bbox_inches='tight')
        plt.close()
        print("  Saved bar plot (all classes)")
    except Exception as e:
        print(f"  Warning: Could not save bar plot: {e}")

    # Individual class summary plots
    for class_idx in range(num_classes):
        try:
            plt.figure(figsize=(12, 8))
            shap.summary_plot(shap_values[class_idx], X_test, show=False)
            class_name = class_names[class_idx] if class_names is not None else f"Class_{class_idx}"
            plt.title(f'SHAP Summary - {class_name}')
            plt.tight_layout()
            plt.savefig(f"{SHAPConfig.OUTPUT_DIR}/summary_plots/shap_summary_class_{class_idx}.png",
                       dpi=150, bbox_inches='tight')
            plt.close()
            print(f"  Saved summary plot for {class_name}")
        except Exception as e:
            print(f"  Warning: Could not save summary plot for class {class_idx}: {e}")


