def load_saved_model(model_dir="models", timestamp=None):
    """Load saved model, scaler, and class names"""
    if timestamp is None:
        model_files = glob.glob(f"{model_dir}/model_info_*.json")
        if not model_files:
            print("No saved model found!")
            return None, None, None
        latest_file = max(model_files, key=os.path.getctime)
        with open(latest_file, 'r') as f:
            model_info = json.load(f)
        print(f"Loading latest model: {os.path.basename(latest_file)}")
    else:
        info_path = f"{model_dir}/model_info_{timestamp}.json"
        with open(info_path, 'r') as f:
            model_info = json.load(f)
        print(f"Loading model with timestamp: {timestamp}")

    model = xgb.Booster()
    model.load_model(model_info['model_path'])
    print(f"  - Model loaded: {model_info['model_path']}")

    scaler = joblib.load(model_info['scaler_path'])
    print(f"  - Scaler loaded: {model_info['scaler_path']}")

    class_names = np.load(model_info['class_names_path'], allow_pickle=True)
    print(f"  - Class names: {class_names}")
    print(f"  - Number of classes: {len(class_names)}")

    return model, scaler, class_names, model_info


def load_test_data(features_path, labels_path):
    """Load test features and labels"""
    X_test = pd.read_csv(features_path).values
    y_test = pd.read_csv(labels_path).values.flatten()
    print(f"Test data loaded: {X_test.shape[0]} samples, {X_test.shape[1]} features")
    return X_test, y_test


